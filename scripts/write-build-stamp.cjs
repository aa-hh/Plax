/**
 * Writes dist/.plax-build-stamp.json after rollup build.
 * Compares src fingerprints to .build-last-stamp.json for change summary.
 */
var fs = require('fs');
var path = require('path');
var lib = require('./build-stamp-lib.cjs');

var projectRoot = path.join(__dirname, '..');
var dist = path.join(projectRoot, 'dist');
var appJsPath = path.join(dist, 'app.js');

if (!fs.existsSync(appJsPath)) {
  console.error('write-build-stamp: dist/app.js missing — run npm run build first');
  process.exit(1);
}

var stamp = lib.createBuildStamp(projectRoot);

fs.writeFileSync(
  path.join(dist, '.plax-build-stamp.json'),
  JSON.stringify(stamp, null, 2) + '\n'
);

var runtimeStamp = {
  buildNumber: stamp.buildNumber,
  builtAt: stamp.builtAt,
  gitCommit: stamp.gitCommit,
  gitBranch: stamp.gitBranch,
  gitDirty: stamp.gitDirty,
  summary: stamp.summary
};
fs.writeFileSync(
  path.join(dist, 'build-info.js'),
  '// Generated by write-build-stamp.cjs — do not edit\n' +
    'window.__PLAX_BUILD__ = ' + JSON.stringify(runtimeStamp) + ';\n'
);

if (process.argv.indexOf('--quiet') < 0) {
  lib.formatStampDetail(stamp).forEach(function (line) {
    console.log(line);
  });
}
